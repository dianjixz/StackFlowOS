/* language state                                                      */
/* ------------------------------------------------------------------ */

function readStoredLang() {
  try {
    const stored = window.localStorage.getItem(LANG_STORAGE_KEY);
    if (stored && LANGS.includes(stored)) return stored;
  } catch {
    /* private mode / storage disabled: fall back to zh */
  }
  return 'zh';
}

let currentLang = readStoredLang();

export function getLang() {
  return currentLang;
}

/** True when the active language has an explicit translation for `key`. */
export function hasKey(key, lang = currentLang) {
  return Boolean(DICTS[lang] && Object.prototype.hasOwnProperty.call(DICTS[lang], key));
}

/**
 * Translate `key` with `{param}` interpolation.
 * Lookup order: active language → zh → explicit fallback → key.
 * @param {string} key
 * @param {Record<string, string|number>} [params]
 * @param {string|null} [fallback]
 */
export function t(key, params = {}, fallback = null) {
  const active = DICTS[currentLang] || DICTS.zh;
  let text = active[key];
  if (text === undefined) text = DICTS.zh[key];
  if (text === undefined) text = fallback !== null && fallback !== undefined ? fallback : key;
  return String(text).replace(/\{(\w+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
  ));
}

/** Replace the static copy inside `root` from data-i18n* attributes. */
export function applyI18n(root = document) {
  if (!root || typeof root.querySelectorAll !== 'function') return;
  for (const node of root.querySelectorAll('[data-i18n]')) {
    node.textContent = t(node.dataset.i18n);
  }
  for (const node of root.querySelectorAll('[data-i18n-title]')) {
    node.title = t(node.dataset.i18nTitle);
  }
  for (const node of root.querySelectorAll('[data-i18n-aria-label]')) {
    node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel));
  }
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) {
    node.setAttribute('placeholder', t(node.dataset.i18nPlaceholder));
  }
}

/**
 * Switch language. Persists locally (best effort), updates static markup and
 * publishes `on('lang')` so dynamic views can re-render without a reload.
 */
export function setLang(lang, { silent = false } = {}) {
  const next = LANGS.includes(lang) ? lang : 'zh';
  currentLang = next;
  try {
    window.localStorage.setItem(LANG_STORAGE_KEY, next);
  } catch {
    /* ignore quota/private-mode failures */
  }
  document.documentElement.lang = next === 'en' ? 'en' : 'zh-CN';
  applyI18n(document);
  if (!silent) notify('lang', { lang: next });
  return next;
}

/** Bootstrap: set the document language and translate the static shell. */
export function initI18n() {
  document.documentElement.lang = currentLang === 'en' ? 'en' : 'zh-CN';
  applyI18n(document);
  notify('lang', { lang: currentLang, initial: true });
  return currentLang;
}
